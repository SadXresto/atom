//! Firmware project generation, build and flash.
//!
//! The generated project is a normal PlatformIO project. Building and flashing
//! call `pio` with an explicit argv; when PlatformIO is missing, the step fails
//! with the exact install instruction instead of claiming a build happened.

use crate::hardware::Target;
use crate::project::FirmwareReport;
use atom_core::{AtomError, Result};
use std::path::{Path, PathBuf};

const PIO_INI: &str = r#"; Generated by ATOM Micro
[env:@ENV@]
platform = @PLATFORM@
board = @BOARD@
framework = arduino
build_flags =
    -O2
    -ffast-math
    -DATOM_MICRO_BUILD
monitor_speed = 115200
"#;

const MAIN_CPP: &str = r#"// Generated by ATOM Micro — @PROJECT@
// Serial protocol:
//   "bench"  → prints a measured ATOM benchmark report (JSON)
//   anything else → continues the byte-level model from the given prompt
#include <Arduino.h>
#include "model.h"

static const uint32_t ATOM_WEIGHT_BYTES = ATOM_PARAMS * (ATOM_BITS / 8);
static const uint32_t ATOM_RAM_BYTES =
    ATOM_WEIGHT_BYTES + ATOM_VOCAB * 4 + ATOM_HIDDEN * 4 + ATOM_CONTEXT + 2048;

static uint32_t device_flash_bytes() {
#if defined(ESP32)
    return (uint32_t)ESP.getSketchSize();
#elif defined(ARDUINO_ARCH_RP2040)
    return 0;
#else
    return 0;
#endif
}

static void run_benchmark() {
    uint8_t window[ATOM_CONTEXT];
    float logits[ATOM_VOCAB];
    for (int i = 0; i < ATOM_CONTEXT; i++) window[i] = ' ';
    const int iterations = 256;
    uint32_t start = micros();
    for (int i = 0; i < iterations; i++) {
        window[i % ATOM_CONTEXT] = (uint8_t)('a' + (i % 26));
        atom_forward(window, logits);
        window[(i + 1) % ATOM_CONTEXT] = (uint8_t)(i % 256);
    }
    uint32_t elapsed = micros() - start;
    float tps = elapsed ? (iterations * 1000000.0f) / (float)elapsed : 0.0f;
    float latency = tps > 0.0f ? 1000.0f / tps : 0.0f;
    Serial.print("{\"device\":\"");
    Serial.print("@TARGET_NAME@");
    Serial.print("\",\"firmware\":\"atom-micro @VERSION@\",\"runs\":[{\"label\":\"ATOM_BITS=");
    Serial.print(ATOM_BITS);
    Serial.print(" · forward\",\"tokens_per_second\":");
    Serial.print(tps, 3);
    Serial.print(",\"latency_ms\":");
    Serial.print(latency, 3);
    Serial.print(",\"ram_bytes\":");
    Serial.print(ATOM_RAM_BYTES);
    Serial.print(",\"flash_bytes\":");
    Serial.print(device_flash_bytes());
    Serial.print(",\"notes\":\"measured on device with the firmware benchmark command\",");
    Serial.print("\"measured_at\":\"\"}]}");
    Serial.println();
}

void setup() {
    Serial.begin(115200);
    delay(400);
    Serial.println();
    Serial.println("ATOM Micro — @PROJECT@");
    Serial.println("type a prompt and press enter, or 'bench'");
}

void loop() {
    static char line[128];
    static int length = 0;
    while (Serial.available()) {
        char c = (char)Serial.read();
        if (c == '\n' || c == '\r') {
            line[length] = 0;
            if (length > 0) {
                if (strcmp(line, "bench") == 0) {
                    run_benchmark();
                } else {
                    uint8_t out[160];
                    int generated = atom_generate((const uint8_t *)line, length, out, 96, 0.7f,
                                                  (uint32_t)millis());
                    Serial.write(out, generated);
                    Serial.println();
                }
            }
            length = 0;
        } else if (length < (int)sizeof(line) - 1) {
            line[length++] = c;
        }
    }
}
"#;

pub fn generate_project(
    dir: &Path,
    project_name: &str,
    target: &Target,
    export_dir: &Path,
) -> Result<()> {
    let board = target.platformio_board.ok_or_else(|| {
        AtomError::Unavailable(format!(
            "{} is a reference target; firmware is only generated for microcontrollers",
            target.name
        ))
    })?;
    let platform = match target.id {
        "esp32s3" | "esp32c6" | "esp32" => "espressif32",
        "rp2040" => "raspberrypi",
        "stm32f411" => "ststm32",
        "nrf52840" => "nordicnrf52",
        other => {
            return Err(AtomError::Unavailable(format!(
                "no PlatformIO platform is mapped for target '{other}'"
            )))
        }
    };
    std::fs::create_dir_all(dir.join("src"))?;
    let ini = PIO_INI
        .replace("@ENV@", target.id)
        .replace("@PLATFORM@", platform)
        .replace("@BOARD@", board);
    std::fs::write(dir.join("platformio.ini"), ini)?;
    let main = MAIN_CPP
        .replace("@PROJECT@", project_name)
        .replace("@TARGET_NAME@", target.name)
        .replace("@VERSION@", env!("CARGO_PKG_VERSION"));
    std::fs::write(dir.join("src/main.cpp"), main)?;
    for name in ["model.c", "model.h", "runtime.c"] {
        let source = export_dir.join(name);
        if !source.exists() {
            return Err(AtomError::Conflict(format!(
                "the export is missing {name}; run Export before building firmware"
            )));
        }
        std::fs::copy(&source, dir.join("src").join(name))?;
    }
    let readme = format!(
        "# Firmware — {project}\n\nTarget: {name}\nBoard: `{board}`\nPlatform: `{platform}`\n\n\
         ```sh\npio run            # build\npio run -t upload  # flash a connected board\npio device monitor -b 115200\n```\n\n\
         The serial console accepts plain prompts and the `bench` command, which prints a\n\
         measured benchmark report you can import in ATOM.\n",
        project = project_name,
        name = target.name,
        board = board,
        platform = platform,
    );
    std::fs::write(dir.join("README.md"), readme)?;
    Ok(())
}

pub fn build(dir: &Path, cancel: impl Fn() -> bool, log: impl FnMut(&str)) -> Result<FirmwareReport> {
    let pio = crate::tools::find_program("pio").ok_or_else(|| {
        AtomError::Unavailable(
            "PlatformIO Core (`pio`) was not found on PATH. Install it with `pip install platformio`, \
             then run the build again."
                .into(),
        )
    })?;
    let mut tail: Vec<String> = Vec::new();
    let mut log = log;
    let success = crate::tools::run_tool(
        &pio,
        &["run", "-d", &dir.display().to_string()],
        None,
        |line| {
            tail.push(line.to_string());
            if tail.len() > 400 {
                tail.remove(0);
            }
            log(line);
        },
        cancel,
        std::time::Duration::from_secs(900),
    )
    .map_err(|e| match e.kind() {
        std::io::ErrorKind::Interrupted => AtomError::Cancelled("firmware build cancelled".into()),
        _ => AtomError::Unavailable(format!("could not run PlatformIO: {e}")),
    })?;
    let artifact = find_firmware(dir);
    let report = FirmwareReport {
        dir: dir.display().to_string(),
        target_id: String::new(),
        board: String::new(),
        generated_at: chrono::Local::now().to_rfc3339(),
        built: success,
        build_tool: pio.display().to_string(),
        artifact_path: artifact,
        log_tail: tail.iter().rev().take(120).cloned().collect::<Vec<_>>().into_iter().rev().collect(),
        error: if success {
            None
        } else {
            Some("PlatformIO reported a build failure; see the log tail".into())
        },
        deployed: false,
        deployed_at: None,
    };
    Ok(report)
}

pub fn upload(dir: &Path, cancel: impl Fn() -> bool, log: impl FnMut(&str)) -> Result<Vec<String>> {
    let pio = crate::tools::find_program("pio").ok_or_else(|| {
        AtomError::Unavailable(
            "PlatformIO Core (`pio`) was not found on PATH, so flashing is unavailable. \
             Install it with `pip install platformio` and connect the board."
                .into(),
        )
    })?;
    let mut tail: Vec<String> = Vec::new();
    let mut log = log;
    let success = crate::tools::run_tool(
        &pio,
        &["run", "-d", &dir.display().to_string(), "-t", "upload"],
        None,
        |line| {
            tail.push(line.to_string());
            if tail.len() > 400 {
                tail.remove(0);
            }
            log(line);
        },
        cancel,
        std::time::Duration::from_secs(300),
    )
    .map_err(|e| match e.kind() {
        std::io::ErrorKind::Interrupted => AtomError::Cancelled("flash cancelled".into()),
        _ => AtomError::Unavailable(format!("could not run PlatformIO upload: {e}")),
    })?;
    if !success {
        return Err(AtomError::Backend(
            "the upload failed. Check that the board is connected and the port is free; \
             the log tail has the tool's own error."
                .into(),
        ));
    }
    Ok(tail.into_iter().rev().take(40).collect::<Vec<_>>().into_iter().rev().collect())
}

pub fn find_firmware(dir: &Path) -> Option<String> {
    let pio_build = dir.join(".pio/build");
    let entries = std::fs::read_dir(pio_build).ok()?;
    let mut newest: Option<(std::time::SystemTime, PathBuf)> = None;
    for entry in entries.flatten() {
        let firmware = entry.path().join("firmware.bin");
        let elf = entry.path().join("firmware.elf");
        for candidate in [firmware, elf] {
            if let Ok(meta) = std::fs::metadata(&candidate) {
                if meta.len() == 0 {
                    continue;
                }
                let modified = meta.modified().unwrap_or(std::time::UNIX_EPOCH);
                if newest.as_ref().map(|(t, _)| modified > *t).unwrap_or(true) {
                    newest = Some((modified, candidate));
                }
            }
        }
    }
    newest.map(|(_, path)| path.display().to_string())
}

pub fn project_dir(root: &Path, project_id: &str) -> PathBuf {
    root.join(project_id)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn project_generation_writes_platformio_files() {
        let export = tempfile::tempdir().unwrap();
        std::fs::write(export.path().join("model.c"), "// model").unwrap();
        std::fs::write(export.path().join("model.h"), "// header").unwrap();
        std::fs::write(export.path().join("runtime.c"), "// runtime").unwrap();
        let dir = tempfile::tempdir().unwrap();
        let target = crate::hardware::target("esp32s3").unwrap();
        generate_project(dir.path(), "demo", target, export.path()).unwrap();
        assert!(dir.path().join("platformio.ini").exists());
        assert!(dir.path().join("src/main.cpp").exists());
        let ini = std::fs::read_to_string(dir.path().join("platformio.ini")).unwrap();
        assert!(ini.contains("esp32-s3-devkitc-1"));
    }

    #[test]
    fn host_target_has_no_firmware() {
        let dir = tempfile::tempdir().unwrap();
        let target = crate::hardware::target("host").unwrap();
        assert!(generate_project(dir.path(), "demo", target, dir.path()).is_err());
    }
}
