//! Deployment artifact export.
//!
//! An export is a directory containing the packed quantized weights, a portable
//! C implementation of the model, a generated model.c/model.h pair, a host CLI
//! that can benchmark the artifact, a JSON manifest with checksums, and a
//! README. Where a C compiler is available the generated code is compiled and
//! executed, and the result is recorded in the report.

use crate::hardware::{MemoryPlan, Target};
use crate::model::QuantizedModel;
use crate::project::ExportFile;
use atom_core::{AtomError, Result};
use serde::Serialize;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

#[derive(Serialize)]
struct ManifestModel {
    format: String,
    params: u64,
    weight_bytes: u64,
    f32_bytes: u64,
    context: u32,
    hidden: u32,
    architecture: String,
    dataset_documents: Option<usize>,
    validation_perplexity: Option<f64>,
}

#[derive(Serialize)]
struct ManifestFile {
    name: String,
    bytes: u64,
    sha256: String,
}

#[derive(Serialize)]
struct Manifest {
    schema: &'static str,
    project: String,
    created_at: String,
    model: ManifestModel,
    target: String,
    memory: Option<MemoryPlan>,
    quantization_report: Option<serde_json::Value>,
    files: Vec<ManifestFile>,
    note: &'static str,
}

pub struct ExportInput<'a> {
    pub project_name: &'a str,
    pub architecture: &'a str,
    pub dataset_documents: Option<usize>,
    pub validation_perplexity: Option<f64>,
    pub target: &'a Target,
    pub memory: Option<&'a MemoryPlan>,
    pub quantization_report: Option<serde_json::Value>,
}

fn array_i8(name: &str, values: &[u8]) -> String {
    let mut out = String::with_capacity(values.len() * 4 + 64);
    let _ = write!(out, "const signed char {name}[{}] = {{\n", values.len());
    for chunk in values.chunks(24) {
        for value in chunk {
            let _ = write!(out, "{},", *value as i8);
        }
        out.push('\n');
    }
    out.push_str("};\n\n");
    out
}

fn array_u8(name: &str, values: &[u8]) -> String {
    let mut out = String::with_capacity(values.len() * 4 + 64);
    let _ = write!(out, "const unsigned char {name}[{}] = {{\n", values.len());
    for chunk in values.chunks(24) {
        for value in chunk {
            let _ = write!(out, "{}u,", value);
        }
        out.push('\n');
    }
    out.push_str("};\n\n");
    out
}

fn array_f32(name: &str, values: &[f32]) -> String {
    let mut out = String::with_capacity(values.len() * 12 + 64);
    let _ = write!(out, "const float {name}[{}] = {{\n", values.len());
    for chunk in values.chunks(12) {
        for value in chunk {
            let _ = write!(out, "{:.9}f,", value);
        }
        out.push('\n');
    }
    out.push_str("};\n\n");
    out
}

pub fn generate_c_files(model: &QuantizedModel, dir: &Path) -> Result<()> {
    std::fs::create_dir_all(dir)?;
    let ctx = model.context;
    let hidden = model.hidden;
    let bits = model.bits;
    let mut header = String::new();
    let _ = write!(
        header,
        "/* Generated by ATOM Micro. Do not edit. */\n\
         #ifndef ATOM_MODEL_H\n#define ATOM_MODEL_H\n#include <stdint.h>\n\n\
         #define ATOM_CONTEXT {ctx}\n#define ATOM_HIDDEN {hidden}\n#define ATOM_VOCAB 256\n\
         #define ATOM_BITS {bits}\n#define ATOM_PARAMS {}\n\
         #define ATOM_IN_DIM (ATOM_CONTEXT * ATOM_VOCAB)\n\n",
        model.params()
    );
    header.push_str("extern const float atom_b1[ATOM_HIDDEN];\nextern const float atom_b2[ATOM_VOCAB];\n");
    header.push_str("extern const float atom_w1_scale[ATOM_HIDDEN];\nextern const float atom_w2_scale[ATOM_VOCAB];\n");
    match bits {
        8 => {
            header.push_str("extern const signed char atom_w1[ATOM_HIDDEN * ATOM_IN_DIM];\n");
            header.push_str("extern const signed char atom_w2[ATOM_VOCAB * ATOM_HIDDEN];\n");
        }
        4 => {
            header.push_str("extern const unsigned char atom_w1[ATOM_HIDDEN * ATOM_IN_DIM / 2];\n");
            header.push_str("extern const unsigned char atom_w2[ATOM_VOCAB * ATOM_HIDDEN / 2];\n");
        }
        _ => {
            header.push_str("extern const float atom_w1[ATOM_HIDDEN * ATOM_IN_DIM];\n");
            header.push_str("extern const float atom_w2[ATOM_VOCAB * ATOM_HIDDEN];\n");
        }
    }
    header.push_str(
        "\nvoid atom_forward(const uint8_t *context, float *logits);\n\
         int atom_generate(const uint8_t *prompt, int prompt_len, uint8_t *out, int max_tokens,\n\
         \x20                 float temperature, uint32_t seed);\n\
         uint32_t atom_rng_next(void);\n#endif\n",
    );
    std::fs::write(dir.join("model.h"), header)?;

    let mut source = String::from("/* Generated by ATOM Micro. Do not edit. */\n#include \"model.h\"\n\n");
    source.push_str(&array_f32("atom_b1", &model.b1));
    source.push_str(&array_f32("atom_b2", &model.b2));
    source.push_str(&array_f32("atom_w1_scale", &model.w1.scales));
    source.push_str(&array_f32("atom_w2_scale", &model.w2.scales));
    match bits {
        8 => {
            source.push_str(&array_i8("atom_w1", &model.w1.data));
            source.push_str(&array_i8("atom_w2", &model.w2.data));
        }
        4 => {
            source.push_str(&array_u8("atom_w1", &model.w1.data));
            source.push_str(&array_u8("atom_w2", &model.w2.data));
        }
        _ => {
            let weights = model.dequantized();
            source.push_str(&array_f32("atom_w1", &weights.w1));
            source.push_str(&array_f32("atom_w2", &weights.w2));
        }
    }
    std::fs::write(dir.join("model.c"), source)?;
    std::fs::write(dir.join("runtime.c"), RUNTIME_C)?;
    std::fs::write(dir.join("main.c"), HOST_MAIN_C)?;
    Ok(())
}

const RUNTIME_C: &str = r#"/* ATOM Micro reference runtime. Generated from the model layout. */
#include "model.h"
#include <math.h>
#include <string.h>

static uint32_t g_rng = 1u;

uint32_t atom_rng_next(void) {
    g_rng ^= g_rng << 13;
    g_rng ^= g_rng >> 17;
    g_rng ^= g_rng << 5;
    return g_rng;
}

#if ATOM_BITS == 8
static inline float w1_at(int row, int col) {
    return (float)atom_w1[row * ATOM_IN_DIM + col] * atom_w1_scale[row];
}
static inline float w2_at(int row, int col) {
    return (float)atom_w2[row * ATOM_HIDDEN + col] * atom_w2_scale[row];
}
#elif ATOM_BITS == 4
static inline float nibble(const unsigned char *arr, int index, float scale) {
    unsigned char byte = arr[index >> 1];
    int value = (index & 1) ? (byte >> 4) : (byte & 0x0f);
    if (value >= 8) value -= 16;
    return (float)value * scale;
}
static inline float w1_at(int row, int col) {
    return nibble(atom_w1, row * ATOM_IN_DIM + col, atom_w1_scale[row]);
}
static inline float w2_at(int row, int col) {
    return nibble(atom_w2, row * ATOM_HIDDEN + col, atom_w2_scale[row]);
}
#else
static inline float w1_at(int row, int col) { return atom_w1[row * ATOM_IN_DIM + col]; }
static inline float w2_at(int row, int col) { return atom_w2[row * ATOM_HIDDEN + col]; }
#endif

void atom_forward(const uint8_t *context, float *logits) {
    float hidden[ATOM_HIDDEN];
    for (int k = 0; k < ATOM_HIDDEN; k++) hidden[k] = atom_b1[k];
    for (int pos = 0; pos < ATOM_CONTEXT; pos++) {
        int base = pos * ATOM_VOCAB + (int)context[pos];
        for (int k = 0; k < ATOM_HIDDEN; k++) hidden[k] += w1_at(k, base);
    }
    for (int k = 0; k < ATOM_HIDDEN; k++) if (hidden[k] < 0.0f) hidden[k] = 0.0f;
    for (int v = 0; v < ATOM_VOCAB; v++) {
        float sum = atom_b2[v];
        for (int k = 0; k < ATOM_HIDDEN; k++) sum += w2_at(v, k) * hidden[k];
        logits[v] = sum;
    }
}

int atom_generate(const uint8_t *prompt, int prompt_len, uint8_t *out, int max_tokens,
                  float temperature, uint32_t seed) {
    uint8_t window[ATOM_CONTEXT];
    for (int i = 0; i < ATOM_CONTEXT; i++) window[i] = ' ';
    int copy = prompt_len < ATOM_CONTEXT ? prompt_len : ATOM_CONTEXT;
    for (int i = 0; i < copy; i++) window[ATOM_CONTEXT - copy + i] = prompt[prompt_len - copy + i];
    g_rng = seed ? seed : 1u;
    float logits[ATOM_VOCAB];
    float temp = temperature < 0.05f ? 0.05f : temperature;
    for (int t = 0; t < max_tokens; t++) {
        atom_forward(window, logits);
        float max = logits[0];
        for (int v = 1; v < ATOM_VOCAB; v++) if (logits[v] > max) max = logits[v];
        float sum = 0.0f;
        for (int v = 0; v < ATOM_VOCAB; v++) {
            logits[v] = expf((logits[v] - max) / temp);
            sum += logits[v];
        }
        float target = ((float)(atom_rng_next() >> 8) / 16777216.0f) * sum;
        float acc = 0.0f;
        int chosen = 0;
        for (int v = 0; v < ATOM_VOCAB; v++) {
            acc += logits[v];
            if (acc >= target) { chosen = v; break; }
        }
        out[t] = (uint8_t)chosen;
        for (int i = 1; i < ATOM_CONTEXT; i++) window[i - 1] = window[i];
        window[ATOM_CONTEXT - 1] = (uint8_t)chosen;
    }
    return max_tokens;
}
"#;

const HOST_MAIN_C: &str = r#"/* Host harness for an exported ATOM Micro model.
 *   ./atom_model "prompt"        generate 64 bytes
 *   ./atom_model --bench 500     measure forward passes per second
 */
#include "model.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

static double now_seconds(void) {
    /* Portable CPU clock: no POSIX feature-test macros required. */
    return (double)clock() / (double)CLOCKS_PER_SEC;
}

int main(int argc, char **argv) {
    uint8_t out[512];
    if (argc >= 3 && strcmp(argv[1], "--bench") == 0) {
        int iterations = atoi(argv[2]);
        if (iterations <= 0) iterations = 100;
        uint8_t window[ATOM_CONTEXT];
        float logits[ATOM_VOCAB];
        for (int i = 0; i < ATOM_CONTEXT; i++) window[i] = ' ';
        double start = now_seconds();
        for (int i = 0; i < iterations; i++) {
            window[i % ATOM_CONTEXT] = (uint8_t)('a' + (i % 26));
            atom_forward(window, logits);
            window[(i + 1) % ATOM_CONTEXT] = (uint8_t)(i % 256);
        }
        double elapsed = now_seconds() - start;
        double tps = iterations / (elapsed > 1e-9 ? elapsed : 1e-9);
        printf("{\"device\":\"host-reference\",\"firmware\":\"atom-export\",\"runs\":[{"
               "\"label\":\"ATOM_BITS=%d\",\"tokens_per_second\":%.3f,\"latency_ms\":%.3f,"
               "\"ram_bytes\":%d,\"flash_bytes\":%d,"
               "\"notes\":\"measured by the exported host harness\"}]}\n",
               ATOM_BITS, tps, 1000.0 / (tps > 1e-9 ? tps : 1e-9),
               ATOM_PARAMS * (ATOM_BITS / 8) + 4096, ATOM_PARAMS * (ATOM_BITS / 8));
        return 0;
    }
    const char *prompt = argc >= 2 ? argv[1] : "LED";
    int generated = atom_generate((const uint8_t *)prompt, (int)strlen(prompt), out, 64, 0.7f, 12345u);
    fwrite(out, 1, (size_t)generated, stdout);
    printf("\n");
    return 0;
}
"#;

fn sha(path: &Path) -> Result<(String, u64)> {
    atom_security::sha256_file(path)
}

pub fn export_bundle(
    model: &QuantizedModel,
    dir: &Path,
    input: &ExportInput<'_>,
) -> Result<crate::project::ExportReport> {
    std::fs::create_dir_all(dir)?;
    let model_path = dir.join("model.bin");
    model.write_container(&model_path)?;
    generate_c_files(model, dir)?;

    let mut files: Vec<ExportFile> = Vec::new();
    for name in ["model.bin", "model.c", "model.h", "runtime.c", "main.c"] {
        let path = dir.join(name);
        let (sha256, bytes) = sha(&path)?;
        files.push(ExportFile {
            name: name.to_string(),
            bytes,
            sha256,
        });
    }

    let manifest = Manifest {
        schema: "atom.micro.export/1",
        project: input.project_name.to_string(),
        created_at: chrono::Local::now().to_rfc3339(),
        model: ManifestModel {
            format: model.format.clone(),
            params: model.params(),
            weight_bytes: model.weight_bytes,
            f32_bytes: model.f32_bytes(),
            context: model.context as u32,
            hidden: model.hidden as u32,
            architecture: input.architecture.to_string(),
            dataset_documents: input.dataset_documents,
            validation_perplexity: input.validation_perplexity,
        },
        target: input.target.id.to_string(),
        memory: input.memory.cloned(),
        quantization_report: input.quantization_report.clone(),
        files: files
            .iter()
            .map(|f| ManifestFile {
                name: f.name.clone(),
                bytes: f.bytes,
                sha256: f.sha256.clone(),
            })
            .collect(),
        note: "Checksums are SHA-256 of the files in this directory. The C files implement the \
               model exactly as stored in model.bin for this quantization format.",
    };
    let manifest_path = dir.join("manifest.json");
    std::fs::write(&manifest_path, serde_json::to_string_pretty(&manifest)?)?;
    let (manifest_sha, manifest_bytes) = sha(&manifest_path)?;
    files.push(ExportFile {
        name: "manifest.json".into(),
        bytes: manifest_bytes,
        sha256: manifest_sha.clone(),
    });

    let readme = format!(
        "# {project} — ATOM Micro export\n\n\
         Format: {format} · {params} parameters · context {context} · hidden {hidden}\n\
         Target: {target}\n\n\
         ## Files\n\n\
         - `model.bin` — packed weights (ATOMQ1 container)\n\
         - `model.c` / `model.h` — the same weights as C arrays\n\
         - `runtime.c` — reference inference implementation (no dependencies beyond libm)\n\
         - `main.c` — host harness: `cc -O2 -o atom_model main.c runtime.c model.c -lm`\n\
         - `manifest.json` — sizes and SHA-256 for every file\n\n\
         ## Run on this computer\n\n\
         ```sh\n\
         cc -O2 -std=c11 -o atom_model main.c runtime.c model.c -lm\n\
         ./atom_model \"LED\"          # generate 64 bytes\n\
         ./atom_model --bench 2000   # measured forward passes per second\n\
         ```\n\n\
         The `--bench` output is a valid ATOM device benchmark report; paste it into the\n\
         Benchmark step to record measured numbers.\n",
        project = input.project_name,
        format = model.format,
        params = model.params(),
        context = model.context,
        hidden = model.hidden,
        target = input.target.name,
    );
    std::fs::write(dir.join("README.md"), readme)?;
    let (readme_sha, readme_bytes) = sha(&dir.join("README.md"))?;
    files.push(ExportFile {
        name: "README.md".into(),
        bytes: readme_bytes,
        sha256: readme_sha,
    });

    let compile_check = compile_and_run(dir);
    let total_bytes = files.iter().map(|f| f.bytes).sum();
    Ok(crate::project::ExportReport {
        dir: dir.display().to_string(),
        created_at: chrono::Local::now().to_rfc3339(),
        files,
        manifest_path: manifest_path.display().to_string(),
        manifest_sha256: manifest_sha,
        quant_format: model.format.clone(),
        compile_check,
        total_bytes,
    })
}

fn compile_and_run(dir: &Path) -> Option<String> {
    let cc = crate::tools::find_program("cc")
        .or_else(|| crate::tools::find_program("gcc"))
        .or_else(|| crate::tools::find_program("clang"))?;
    let binary = dir.join(if cfg!(windows) { "atom_model.exe" } else { "atom_model" });
    let compile = std::process::Command::new(&cc)
        .args(["-O2", "-std=c11", "-o"])
        .arg(&binary)
        .args(["main.c", "runtime.c", "model.c", "-lm"])
        .current_dir(dir)
        .output()
        .ok()?;
    if !compile.status.success() {
        let err = String::from_utf8_lossy(&compile.stderr);
        return Some(format!(
            "compilation failed: {}",
            err.lines().next().unwrap_or("unknown compiler error")
        ));
    }
    let run = std::process::Command::new(&binary)
        .args(["--bench", "300"])
        .current_dir(dir)
        .output()
        .ok()?;
    if !run.status.success() {
        return Some("compiled, but the benchmark harness exited with an error".into());
    }
    let text = String::from_utf8_lossy(&run.stdout);
    let line = text.lines().next().unwrap_or("").trim().to_string();
    if line.starts_with('{') {
        Some(format!("compiled with {} and measured: {}", cc.display(), line))
    } else {
        Some(format!("compiled with {} (no measurement output)", cc.display()))
    }
}

pub fn export_dir_name(project: &str, format: &str) -> String {
    let slug: String = project
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '-' })
        .collect();
    let slug = slug.trim_matches('-').to_string();
    format!("{slug}-{format}")
}

pub fn ensure_dir(path: PathBuf) -> Result<PathBuf> {
    if path.as_os_str().is_empty() {
        return Err(AtomError::Invalid("export directory is empty".into()));
    }
    std::fs::create_dir_all(&path)?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::ByteMlp;

    #[test]
    fn export_writes_manifest_and_compiles() {
        let model = ByteMlp::new(4, 8, 1);
        let quant = model.quantize("int8").unwrap();
        let dir = tempfile::tempdir().unwrap();
        let target = crate::hardware::target("esp32s3").unwrap();
        let report = export_bundle(
            &quant,
            dir.path(),
            &ExportInput {
                project_name: "Test project",
                architecture: "Atom MLP · Tiny",
                dataset_documents: Some(10),
                validation_perplexity: Some(4.2),
                target,
                memory: None,
                quantization_report: None,
            },
        )
        .unwrap();
        assert!(report.files.iter().any(|f| f.name == "manifest.json"));
        assert!(report.total_bytes > 0);
        assert!(report.compile_check.is_some());
    }
}
